CREATE TABLE IF NOT EXISTS challenges (
  id TEXT PRIMARY KEY, profile_id TEXT NOT NULL, email TEXT NOT NULL,
  code_hash TEXT NOT NULL, expires_at INTEGER NOT NULL,
  attempts INTEGER NOT NULL DEFAULT 0, consumed INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS rate_limits (
  key TEXT PRIMARY KEY, count INTEGER NOT NULL, expires_at INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS requests (
  id TEXT PRIMARY KEY, envelope TEXT NOT NULL, saved INTEGER NOT NULL DEFAULT 0,
  created_at INTEGER NOT NULL
);
